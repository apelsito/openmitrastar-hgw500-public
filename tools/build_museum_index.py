#!/usr/bin/env python3
"""Generate the deterministic Lyoko milestone index."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MUSEUM = ROOT / "docs/museum"
OUTPUT = MUSEUM / "README.md"
MANIFEST = MUSEUM / "manifest.json"
DATE_RE = re.compile(r"^(?:Date|Fecha):\s*`?(\d{4}-\d{2}-\d{2})`?\s*$", re.MULTILINE)
TITLE_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)


@dataclass(frozen=True)
class Entry:
    date: str
    title: str
    filename: str


def read_entries() -> list[Entry]:
    entries: list[Entry] = []
    for path in sorted(MUSEUM.glob("*.md")):
        if path.name == OUTPUT.name:
            continue
        text = path.read_text(encoding="utf-8")
        title = TITLE_RE.search(text)
        date = DATE_RE.search(text)
        if not title:
            raise ValueError(f"missing H1 title: {path}")
        entries.append(Entry(date.group(1) if date else "undated", title.group(1), path.name))
    return sorted(entries, key=lambda entry: (entry.date != "undated", entry.date, entry.filename), reverse=True)


def render(entries: list[Entry]) -> str:
    lines = [
        "# Lyoko Commit Museum",
        "",
        "Generated by `tools/build_museum_index.py`. Each entry records a technical",
        "milestone, its evidence and the remaining regression boundary.",
        "",
    ]
    current_date = None
    for entry in entries:
        if entry.date != current_date:
            current_date = entry.date
            lines.extend((f"## {current_date}", ""))
        lines.append(f"- [{entry.title}]({entry.filename})")
    lines.append("")
    return "\n".join(lines)


def render_manifest(entries: list[Entry]) -> str:
    payload = {
        "schema": "openmitrastar.museum-manifest/v1",
        "entries": [
            {
                "date": entry.date,
                "file": entry.filename,
                "sha256": hashlib.sha256((MUSEUM / entry.filename).read_bytes()).hexdigest(),
                "title": entry.title,
            }
            for entry in entries
        ],
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when README.md is not current")
    args = parser.parse_args()
    entries = read_entries()
    rendered = render(entries)
    manifest = render_manifest(entries)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit("museum index is stale; run tools/build_museum_index.py")
        if not MANIFEST.exists() or MANIFEST.read_text(encoding="utf-8") != manifest:
            raise SystemExit("museum manifest is stale; run tools/build_museum_index.py")
        print(f"LYOKO_MUSEUM_INDEX_PASS entries={len(entries)}")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    MANIFEST.write_text(manifest, encoding="utf-8", newline="\n")
    print(f"LYOKO_MUSEUM_INDEX_WRITTEN entries={len(entries)} path={OUTPUT} manifest={MANIFEST}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
